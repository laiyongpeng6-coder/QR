/**
 * Fast QR Scan application theme.
 *
 * Applies Material 3 theming with light/dark color schemes and custom typography.
 * On Android 12+ (API 31), dynamic color is supported but we use our branded palette
 * by default for consistent branding across devices.
 *
 * @param darkTheme Whether to use the dark color scheme. Defaults to system setting.
 * @param dynamicColor Whether to use dynamic color on supported devices. Defaults to false
 *   to maintain consistent brand identity.
 * @param content The composable content to be themed.
 */
@Composable
fun FastQrScanTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = FastQrScanTypography,
        content = content
    )
}
